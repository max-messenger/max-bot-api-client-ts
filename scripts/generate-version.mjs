import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
const version = pkg.version;

if (typeof version !== 'string' || version.length === 0) {
  throw new Error(`[generate-version] Cannot resolve version from package.json (got: ${String(version)})`);
}

const output = resolve(root, 'src/version.g.ts');

const content = `// AUTO-GENERATED by scripts/generate-version.mjs from package.json — do not edit.
export const CLIENT_VERSION = ${JSON.stringify(version)};
`;

writeFileSync(output, content, 'utf8');
console.log(`[generate-version] wrote src/version.g.ts (version ${version})`);
